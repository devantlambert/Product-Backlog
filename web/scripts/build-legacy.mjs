// Copies the prototype's screens into the app, with its storage swapped for the database.
// Run `npm run legacy` after the prototype changes. Each patch must match exactly once,
// so a prototype change that moves one of these lines fails loudly here instead of silently.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "..", "prototype", "index.html"), "utf8");

const between = (a, b) => {
  const i = html.indexOf(a);
  const j = html.indexOf(b, i + a.length);
  if (i < 0 || j < 0) throw new Error(`Couldn't find ${a} … ${b}`);
  return html.slice(i + a.length, j);
};

const css = between("<style>", "</style>");
let markup = between("</style>", "<script>").trim();
let js = between("<script>", "</script>");

function patch(where, from, to) {
  const src = where === "js" ? js : markup;
  const n = src.split(from).length - 1;
  if (n !== 1) throw new Error(`Patch for ${where} matched ${n} times: ${from.slice(0, 80)}`);
  const out = src.replace(from, to);
  if (where === "js") js = out;
  else markup = out;
}

// storage: the store has already loaded the state before this script runs
patch(
  "js",
  "let S; try{S=JSON.parse(localStorage.getItem(KEY))}catch(e){}\nif(!S||S.v!==3)S=seed();",
  "const STORE=window.RoadmapStore;\nlet S=STORE.initial; const freshSeed=!S;\nif(!S||S.v!==3)S=seed();",
);
patch("js", "function save(){try{localStorage.setItem(KEY,JSON.stringify(S))}catch(e){}}", "function save(){STORE.save(S)}\nif(freshSeed&&STORE.canEdit())save();");
patch("js", "const canEdit=()=>R().edit;", "const canEdit=()=>R().edit&&STORE.canEdit();");
patch("js", "if(act==='reset'){S=seed();", "if(act==='reset'){if(!STORE.confirmReset())return;S=seed();");
// footer: the store fills in where the data lives and who is signed in
patch(
  "markup",
  '<span>Prototype with fictional sample data. Your edits are saved in this browser only. <button class="btn sm ghost" data-act="reset">Reset sample data</button></span>',
  '<span class="store-status"><span id="store-status"></span> <button class="btn sm ghost" data-act="reset" id="store-reset">Reset sample data</button></span>',
);

mkdirSync(join(root, "public", "legacy"), { recursive: true });
writeFileSync(join(root, "public", "legacy", "roadmap.js"), `// Generated by scripts/build-legacy.mjs from prototype/index.html. Don't edit by hand.\n${js}`);
writeFileSync(join(root, "app", "legacy.css"), `/* Generated by scripts/build-legacy.mjs from prototype/index.html. Don't edit by hand. */\n${css}`);
writeFileSync(
  join(root, "lib", "legacy-markup.ts"),
  `// Generated by scripts/build-legacy.mjs from prototype/index.html. Don't edit by hand.\nexport const legacyMarkup = ${JSON.stringify(markup)};\n`,
);
console.log("Legacy screens rebuilt.");
